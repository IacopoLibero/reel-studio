#!/usr/bin/env node
// Turns a folder of images into one TypeScript module of data URIs, so a carousel's Remotion code can use them without a public/ folder.
//   node scripts/carousel/embed-assets.mjs <images folder> <out.ts> [--max-width 1500]
// Each file becomes a key (its name without the extension). Large images are scaled down with ffmpeg; png stays png (keeps transparency), jpg and webp become jpg.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, extname, join } from "node:path";

const [dir, out, ...rest] = process.argv.slice(2);
if (!dir || !out) { console.error("usage: embed-assets.mjs <images folder> <out.ts> [--max-width 1500]"); process.exit(2); }
const maxW = Number(rest[rest.indexOf("--max-width") + 1]) || 1500;
const tmp = mkdtempSync(join(tmpdir(), "embed-"));
const width = (f) => { try { return Number(execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width", "-of", "csv=p=0", f]).toString().trim()); } catch { return 0; } };
const lines = [];
for (const name of readdirSync(dir).sort()) {
  const ext = extname(name).toLowerCase();
  if (![".png", ".jpg", ".jpeg", ".webp"].includes(ext)) continue;
  const src = join(dir, name); const key = basename(name, ext);
  let file = src, mime = ext === ".png" ? "image/png" : "image/jpeg";
  if (ext === ".webp" || width(src) > maxW) {
    file = join(tmp, key + (ext === ".png" ? ".png" : ".jpg")); mime = ext === ".png" ? "image/png" : "image/jpeg";
    execFileSync("ffmpeg", ["-v", "error", "-y", "-i", src, "-vf", `scale='min(${maxW},iw)':-2`, ...(mime === "image/jpeg" ? ["-q:v", "3"] : []), file]);
  }
  lines.push(`  ${JSON.stringify(key)}: "data:${mime};base64,${readFileSync(file).toString("base64")}",`);
}
rmSync(tmp, { recursive: true, force: true });
writeFileSync(out, `// Generated by scripts/carousel/embed-assets.mjs from ${dir}. Do not edit.\nexport const A: Record<string, string> = {\n${lines.join("\n")}\n};\n`);
console.log(`${lines.length} images written to ${out}`);
